/**
 * Every string the page shows, in English and Polish. A component never holds
 * copy of its own: it reads `t.key` (or calls `t.key(…)` for one with values).
 * Both languages carry every key, so switching is a data change.
 */
export type Locale = 'en' | 'pl'

const STORAGE_KEY = 'peerly-locale'

/** The person's language: what they picked on this device, else the browser's. */
export function detectLocale(stored: string | null = readStored(), languages: readonly string[] = navigator.languages ?? [navigator.language]): Locale {
  if (stored === 'en' || stored === 'pl') return stored
  return languages.some(language => language?.toLowerCase().startsWith('pl')) ? 'pl' : 'en'
}

function readStored(): string | null {
  try {
    return localStorage.getItem(STORAGE_KEY)
  } catch {
    return null
  }
}

export function storeLocale(locale: Locale): void {
  try {
    localStorage.setItem(STORAGE_KEY, locale)
  } catch {
    // Kept for this page only.
  }
}

const englishPlural = new Intl.PluralRules('en')
const polishPlural = new Intl.PluralRules('pl')

/** `count` with the English form for it. */
const en1 = (count: number, one: string, other: string) => `${count} ${englishPlural.select(count) === 'one' ? one : other}`
/** `count` with the Polish form for it: 1 plik, 2 pliki, 5 plików (and 1,5 pliku). */
const pl1 = (count: number, one: string, few: string, many: string, other = many) => {
  const form = polishPlural.select(count)
  return `${count} ${form === 'one' ? one : form === 'few' ? few : form === 'many' ? many : other}`
}
/** A list of names as a sentence would say it. */
const list = (locale: Locale, names: string[]) => new Intl.ListFormat(locale, { type: 'conjunction' }).format(names)

