import { legalDocs, type LegalDoc, type LegalDocId } from './legalContent.ts'

/** A legal text as the Markdown in docs/legal: the English copy of what the app shows at /privacy and /terms. */
export function legalMarkdown(id: LegalDocId, doc: LegalDoc = legalDocs.en[id]): string {
  const lines = [
    `# ${doc.title}`,
    '',
    `_${doc.updated}_`,
    '',
    `> The English copy of the page the app shows at \`/${id}\`. Generated by \`npm run legal:export\` from`,
    '> `src/legal/legalContent.ts`, which is the text to edit.',
    '',
    doc.intro,
  ]
  for (const section of doc.sections) {
    lines.push('', `## ${section.heading}`)
    for (const block of section.blocks) {
      if ('ul' in block) lines.push('', ...block.ul.map(item => `- ${item}`))
      else if ('note' in block) lines.push('', `> ${block.note}`)
      else lines.push('', block.p)
    }
  }
  return `${lines.join('\n')}\n`
}

/** Where each text's English copy lives. */
export const LEGAL_FILES: Record<LegalDocId, string> = { privacy: 'docs/legal/PRIVACY.md', terms: 'docs/legal/TERMS.md' }
